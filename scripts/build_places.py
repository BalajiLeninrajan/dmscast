#!/usr/bin/env python3
"""Build data/places.tsv, the place name to time zone table behind
"time in medan" and "time in syd".

Inputs:
  cities15000.txt  https://download.geonames.org/export/dump/cities15000.zip
  airports.csv     https://davidmegginson.github.io/ourairports-data/airports.csv

Usage: build_places.py cities15000.txt airports.csv > ../data/places.tsv
"""

import csv
import math
import re
import sys

# Alternate names are mostly other languages; only big cities' ASCII ones
# ("bangalore", "bombay") are worth the space.
ALT_NAME_MIN_POPULATION = 500_000
ASCII_NAME = re.compile(r"^[a-z][a-z .'-]{2,}$")


def load_cities(path):
    cities = []
    with open(path, encoding="utf-8") as f:
        for line in f:
            cols = line.rstrip("\n").split("\t")
            name, ascii_name, alt_names = cols[1], cols[2], cols[3]
            lat, lon, country = float(cols[4]), float(cols[5]), cols[8]
            population, zone = int(cols[14] or 0), cols[17]
            if not zone:
                continue
            names = {name.lower(), ascii_name.lower()}
            alts = set()
            if population >= ALT_NAME_MIN_POPULATION:
                alts = {a.lower() for a in alt_names.split(",") if ASCII_NAME.match(a.lower())} - names
            cities.append((names, alts, lat, lon, country, population, zone))
    return cities


def distance(lat1, lon1, lat2, lon2):
    # Equirectangular is plenty to find the nearest city.
    x = math.radians(lon2 - lon1) * math.cos(math.radians((lat1 + lat2) / 2))
    y = math.radians(lat2 - lat1)
    return x * x + y * y


def main(cities_path, airports_path):
    cities = load_cities(cities_path)
    by_country = {}
    for city in cities:
        by_country.setdefault(city[4], []).append(city)

    # Same name, several cities: the most populous wins ("london"). A real
    # name always beats an alternate one, or Austin's historical "Waterloo"
    # would take the name from Waterloo, Ontario.
    places = {}
    for use_alts in (False, True):
        best = {}
        for names, alts, _, _, _, population, zone in cities:
            for name in alts if use_alts else names:
                if name not in places and (name not in best or population > best[name][0]):
                    best[name] = (population, zone)
        places.update({name: zone for name, (_, zone) in best.items()})

    with open(airports_path, encoding="utf-8") as f:
        for row in csv.DictReader(f):
            code = row["iata_code"].strip().lower()
            if not code or row["type"] not in ("large_airport", "medium_airport"):
                continue
            # A city's own name beats an airport code that spells it.
            if code in places:
                continue
            candidates = by_country.get(row["iso_country"])
            if not candidates:
                continue
            lat, lon = float(row["latitude_deg"]), float(row["longitude_deg"])
            nearest = min(candidates, key=lambda c: distance(lat, lon, c[2], c[3]))
            places[code] = nearest[6]

    write(sys.stdout, places)


def write(out, places):
    # Zones are listed once and places point at them by index, which halves
    # the file. calc.js binary-searches the sorted names without parsing it.
    zones = sorted(set(places.values()))
    index = {zone: i for i, zone in enumerate(zones)}
    out.write("# Place names to time zones. Generated by scripts/build_places.py from\n")
    out.write("# GeoNames (CC BY 4.0, geonames.org) and OurAirports (public domain).\n")
    out.write("# The first other line lists the zones; each place names one by index.\n")
    out.write("\t".join(zones) + "\n")
    for name in sorted(places):
        out.write(f"{name}\t{index[places[name]]}\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
